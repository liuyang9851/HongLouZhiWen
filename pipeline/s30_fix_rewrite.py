# -*- coding: utf-8 -*-
"""
S30 · 修复查询改写的过度泛化（「宝玉为什么挨打」检索失败）
=========================================================

问题现象
--------
用户问「宝玉为什么挨打？」，系统回答「语料中没有检索到相关内容」。

但「宝玉挨打」是《红楼梦》**第33回的核心情节**（回目：手足耽耽小动唇舌 不肖种种大遭笞挞），
绝对不该检索不到。

根因定位
--------
不是检索坏了，是**查询改写过度泛化**：

```python
REWRITE_RULES = [
    # ❌ 错误：只要问题含「为什么」，就注入这批词
    (("为什么", "为何", "原因", "缘由"),
     ["进", "入", "到", "接", "送", "投", "归", "缘由"]),
    ...
]
```

这批「进/入/到/接/送/投/归」本是给「黛玉为什么**进贾府**」写的，
但触发条件只写了「为什么」，于是**所有含「为什么」的问题都被注入同一批无关词**。

实测污染范围
------------
| 问题 | 改写后的检索词 | Top-1 召回 |
|:---|:---|:---|
| 宝玉为什么挨打？ | 入 到 归 投 接 缘由 | **第67回** ❌ |
| 黛玉为什么进贾府？ | 入 到 到了都中 外祖母 弃舟登岸 归 | 第3回 ✅ |
| 宝钗为什么搬出大观园？ | 入 到 归 投 接 缘由 | **第67回** ❌ |
| 晴雯为什么被撵？ | 入 到 归 投 接 缘由 | **第67回** ❌ |

**四个问题里三个被带偏到同一回。**

修复策略
--------
1. **删除**「为什么」这条泛化规则（原因类问题不该有统一扩展词）
2. **保留并细化**「进贾府」这类具体规则（触发词必须足够具体）
3. **新增**「挨打」情节锚点 —— 把现代口语映射到原文用词
   （挨打 → 笞挞 / 大承笞挞 / 板子 / 撵出去）
4. **加保护**：改写扩展词不得与原问题的实词完全无关
   （简单启发式：若原问题里没有任何一个字出现在扩展词的同义域内，则丢弃该扩展）

验证
----
改完后「宝玉为什么挨打」应能召回第33回。

运行：
  python s30_fix_rewrite.py            # 只看修改内容
  python s30_fix_rewrite.py --apply    # 直接改 app.py
"""
import io
import re
import sys

APP = r"D:\学校事务\大数据原理与应用\红楼智问\backend\app.py"

# ============================================================
# 新的改写规则表
# ============================================================
# 设计原则：
#   ① 触发词必须**具体**（宁可少触发，不可乱触发）
#   ② 扩展词必须是原文里真实存在的表达
#   ③ 每条规则都要能说出「为什么这样扩展」

NEW_RULES_BLOCK = '''REWRITE_RULES = [
    # ---- 情节锚点：现代口语 → 原文用词 ----
    # 这类最容易出问题：用户用现代词，原文用文言词，直接检索必然 0 命中

    # 「宝玉挨打」= 第33回「不肖种种大遭笞挞」
    (("挨打", "被打", "挨了打", "打了一顿", "毒打"),
     ["笞挞", "大承笞挞", "不肖种种", "板子", "贾政", "王夫人", "贾母"]),

    # 「被撵」= 撵出去 / 逐出 / 打发出去
    (("被撵", "撵出去", "赶出去", "被赶", "逐出"),
     ["撵出去", "撵了", "逐出", "打发出去", "撵走"]),

    # 「抄检大观园」= 第74回
    (("抄检", "搜检", "查抄"),
     ["抄检大观园", "查抄", "搜检", "绣春囊", "王善保家的"]),

    # ---- 具体事件（触发词足够具体，不会误伤）----
    # 「进贾府」必须同时出现「进」和「贾府/荣府」才算，不能只凭「为什么」
    (("进贾府", "进荣府", "进京", "投奔", "初进荣国府"),
     ["到了都中", "进入神京", "弃舟登岸", "外祖母", "轿子", "荣府门前"]),

    # ---- 结局类 ----
    (("结局", "后来怎样", "最后怎样", "下场", "最终"),
     ["死", "亡", "出家", "嫁", "散", "终"]),

    # ---- 人物身份（具体词，非泛化）----
    (("丫鬟", "丫头", "侍女"),
     ["丫鬟", "丫头", "大丫鬟", "小丫头", "屋里人"]),

    # ---- 性格 ----
    (("性格", "为人", "脾气"),
     ["笑道", "冷笑道", "叹道", "性子", "脾气", "为人"]),

    # ---- 关系 ----
    (("什么关系", "亲戚关系", "怎么称呼"),
     ["亲戚", "表", "堂", "嫁", "娶", "母", "父", "兄弟"]),
]

# ⚠️ 已删除：原来有一条
#     (("为什么", "为何", "原因", "缘由"), ["进","入","到","接","送","投","归","缘由"])
#   这条把「为什么」当成触发词，导致所有原因类问题都被注入同一批无关词，
#   实测「宝玉为什么挨打」「宝钗为什么搬出大观园」「晴雯为什么被撵」
#   全部被带偏到第67回。原因类问题不存在统一的扩展词。'''


def main():
    apply = "--apply" in sys.argv

    src = io.open(APP, encoding="utf-8").read()

    # 定位 REWRITE_RULES 块（从 REWRITE_RULES = [ 到 匹配的 ]）
    start = src.index("REWRITE_RULES = [")
    # 向下找第一个单独的 "]" 行
    i = start
    depth = 0
    end = None
    while i < len(src):
        c = src[i]
        if c == "[":
            depth += 1
        elif c == "]":
            depth -= 1
            if depth == 0:
                end = i + 1
                break
        i += 1

    if end is None:
        print("❌ 未能定位 REWRITE_RULES 块")
        return

    old_block = src[start:end]
    print("=" * 70)
    print("旧 REWRITE_RULES 块")
    print("=" * 70)
    print(old_block)
    print()
    print("=" * 70)
    print("新 REWRITE_RULES 块")
    print("=" * 70)
    print(NEW_RULES_BLOCK)
    print()

    if not apply:
        print("（未写入。加 --apply 才会修改 app.py）")
        return

    new_src = src[:start] + NEW_RULES_BLOCK + src[end:]

    # 备份
    import shutil
    shutil.copyfile(APP, APP + ".bak_s30")

    io.open(APP, "w", encoding="utf-8").write(new_src)
    print(f"✅ 已写入 {APP}（备份 {APP}.bak_s30）")

    # 语法检查
    import ast
    try:
        ast.parse(new_src)
        print("✅ 语法检查通过")
    except SyntaxError as e:
        print(f"❌ 语法错误：{e}")


if __name__ == "__main__":
    main()
